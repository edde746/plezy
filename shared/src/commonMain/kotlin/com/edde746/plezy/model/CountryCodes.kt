/**
 * ISO 3166-1 alpha-2 country codes and their English short names ("United Kingdom", not the official long form): the
 * names metadata chips show. English only; callers fall back to the code itself.
 *
 * Catalog providers disagree on which side they send: Plex Discover sends names ("United States of America"), TMDB and
 * AniList send codes.
 */
object CountryCodes {
    /** The display name for [code], or the normalized code when it isn't a known alpha-2 value (`SU`). */
    fun getDisplayName(code: String): String = getCountryName(code) ?: code.uppercase().trim()

    /** The display name for [code], or null when it isn't a known alpha-2 value. */
    fun getCountryName(code: String): String? {
        val normalized = code.uppercase().trim()
        if (normalized.length != 2) return null
        return COUNTRY_NAMES[normalized]
    }

    /** The alpha-2 code a country [name] (official, short or colloquial, any case) or a known code names; else null. */
    fun getCountryCode(name: String): String? {
        val normalized = name.trim()
        if (normalized.isEmpty()) return null
        if (normalized.length == 2 && normalized.uppercase() in COUNTRY_NAMES) return normalized.uppercase()
        return COUNTRY_CODES_BY_NAME[normalized.lowercase()]
    }

    /** The alpha-2 code for a value that may be a code or a name; else the trimmed, upper-cased value. */
    fun normalizeCode(value: String): String = getCountryCode(value) ?: value.uppercase().trim()
}

