#!/usr/bin/env node
// Unicode CLDR display names supplied by Node's ICU implementation.
// Regenerate deliberately when updating the locale catalog; normal builds use
// the committed data and never require Node, a network, or a translation API.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'lib/i18n/locale_catalog.json'), 'utf8'));
const iso = fs.readFileSync(path.join(root, 'lib/data/iso_639_data.dart'), 'utf8');
const codes = [...new Set([...iso.matchAll(/LanguageEntry\('([a-z]+)'/g)].map(m => m[1]))];
if (codes.length < 150) throw new Error('ISO language table could not be read');
const regions = 'AD AE AF AG AI AL AM AO AQ AR AS AT AU AW AX AZ BA BB BD BE BF BG BH BI BJ BL BM BN BO BQ BR BS BT BV BW BY BZ CA CC CD CF CG CH CI CK CL CM CN CO CR CU CV CW CX CY CZ DE DJ DK DM DO DZ EC EE EG EH ER ES ET FI FJ FK FM FO FR GA GB GD GE GF GG GH GI GL GM GN GP GQ GR GS GT GU GW GY HK HM HN HR HT HU ID IE IL IM IN IO IQ IR IS IT JE JM JO JP KE KG KH KI KM KN KP KR KW KY KZ LA LB LC LI LK LR LS LT LU LV LY MA MC MD ME MF MG MH MK ML MM MN MO MP MQ MR MS MT MU MV MW MX MY MZ NA NC NE NF NG NI NL NO NP NR NU NZ OM PA PE PF PG PH PK PL PM PN PR PS PT PW PY QA RE RO RS RU RW SA SB SC SD SE SG SH SI SJ SK SL SM SN SO SR SS ST SV SX SY SZ TC TD TF TG TH TJ TK TL TM TN TO TR TT TV TW TZ UA UG UM US UY UZ VA VC VE VG VI VN VU WF WS YE YT ZA ZM ZW 419'.split(' ');
const languages = {}, territories = {}, scripts = {}, endonyms = {}, units = {};
const unitIds = ['hour', 'minute', 'second', 'millisecond', 'day', 'week', 'month', 'year',
  'byte', 'kilobyte', 'megabyte', 'gigabyte', 'byte-per-second', 'kilobyte-per-second', 'megabyte-per-second',
  'kilobit-per-second', 'megabit-per-second'];
for (const tag of catalog.locales) {
  const locale = tag === 'zh' ? 'zh-Hans' : tag;
  const ln = new Intl.DisplayNames([locale], {type: 'language', languageDisplay: 'standard'});
  const rn = new Intl.DisplayNames([locale], {type: 'region'});
  const sn = new Intl.DisplayNames([locale], {type: 'script'});
  const collator = new Intl.Collator(locale);
  const names = codes.map(c => [c, ln.of(c)]).sort((a,b) => collator.compare(a[1], b[1]));
  languages[tag] = Object.fromEntries(names);
  territories[tag] = Object.fromEntries(regions.map(c => [c, rn.of(c)]));
  scripts[tag] = Object.fromEntries(['Arab','Cyrl','Deva','Hans','Hant','Hebr','Latn'].map(c => [c,sn.of(c)]));
  endonyms[tag] = new Intl.DisplayNames([locale], {type: 'language', languageDisplay: 'standard'}).of(locale);
  units[tag] = {};
  const rules = new Intl.PluralRules(locale);
  const samples = {};
  for (const n of [...Array.from({length: 201}, (_, i) => i), 1000, 1000000, 0.1, 0.5, 1.1, 2.1]) {
    samples[rules.select(n)] ??= n;
  }
  for (const unit of unitIds) {
    units[tag][unit] = {};
    for (const width of ['narrow', 'short', 'long']) {
      const formatter = new Intl.NumberFormat(locale, {style: 'unit', unit, unitDisplay: width, useGrouping: false});
      units[tag][unit][width] = Object.fromEntries(Object.entries(samples).map(([category, sample]) => {
        let numberWritten = false;
        const pattern = formatter.formatToParts(sample).map(part => {
          if (['integer', 'fraction', 'decimal', 'group', 'minusSign', 'plusSign'].includes(part.type)) {
            if (numberWritten) return '';
            numberWritten = true;
            return '{value}';
          }
          return part.value;
        }).join('');
        return [category, pattern];
      }));
    }
  }
}
// Retain the established language-picker labels.
Object.assign(endonyms, {en:'English', sv:'Svenska', fr:'Français', it:'Italiano', nl:'Nederlands', de:'Deutsch',
  hu:'Magyar', zh:'简体中文', 'zh-Hant':'繁體中文', ko:'한국어', es:'Español', pt:'Português', ja:'日本語',
  ru:'Русский', pl:'Polski', da:'Dansk', nb:'Norsk bokmål', bg:'Български', tr:'Türkçe', az:'Azərbaycanca', kk:'Қазақша', uz:'Oʻzbekcha'});
const dart = value => JSON.stringify(value, null, 2).replace(/\$/g, '\\$');
const out = `// Generated by scripts/codegen/generate_locale_names.mjs. Do not edit.\n// Unicode CLDR ${process.versions.cldr}, ICU ${process.versions.icu}.\n// Data license: https://www.unicode.org/license.txt\n\n` +
  `const localeEndonyms = <String, String>${dart(endonyms)};\n\n` +
  `const localizedLanguageNames = <String, Map<String, String>>${dart(languages)};\n\n` +
  `const localizedTerritoryNames = <String, Map<String, String>>${dart(territories)};\n\n` +
  `const localizedScriptNames = <String, Map<String, String>>${dart(scripts)};\n`;
fs.writeFileSync(path.join(root, 'lib/i18n/locale_names.g.dart'), out);
fs.writeFileSync(path.join(root, 'lib/i18n/locale_units.g.dart'),
  `// Generated from Unicode CLDR ${process.versions.cldr}, ICU ${process.versions.icu}.\n` +
  `// Regenerate: node scripts/codegen/generate_locale_names.mjs\n// Data license: https://www.unicode.org/license.txt\n` +
  `const localizedUnitPatterns = <String, Map<String, Map<String, Map<String, String>>>>${dart(units)};\n`);
console.log(`Generated ${codes.length} language names and ${regions.length} territories for ${catalog.locales.length} locales.`);
