#!/usr/bin/env python3
"""Generate shared's DucetOrder.kt from the pinned Unicode and CLDR collation data in scripts/codegen/data.

The data files are gzip copies of Unicode 13.0's allkeys.txt and CLDR's FractionalUCA.txt (the commit in the file
name), redistributed unmodified under the Unicode License v3; their uncompressed SHA-256 is checked before use.
"""

from __future__ import annotations

import functools
import gzip
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(__file__).resolve().parent / "data"
OUTPUT = ROOT / "shared/src/commonMain/kotlin/com/edde746/plezy/model/DucetOrder.kt"

ALLKEYS = (DATA / "allkeys-13.0.0.txt.gz", "a3255d45b7af97f4dc14fb8364d7573b434425e5c58cacf00d16901ce081c78d")
FRACTIONAL_UCA = (
    DATA / "FractionalUCA-651afecf9ccf1541a49306993e8210fa2209aa0b.txt.gz",
    "a6144d0c8c19cc899a5d2f48fbc14e3e31e819049a73aa86b67111f1f3f81637",
)

KANGXI_FIRST = 0x2F00
KANGXI_LAST = 0x2FD5
UNITS_PER_LINE = 128
LINES_PER_CHUNK = 32

WEIGHT = re.compile(r"\[([.*])([0-9A-Fa-f]{4})\.([0-9A-Fa-f]{4})\.([0-9A-Fa-f]{4})\]")
RADICAL = re.compile(r"^\[radical \d+")

HEADER = """\
// Generated by scripts/codegen/generate_ducet_order.py from DUCET (Unicode 13.0) with CLDR's pinned CJK radical-stroke order and root kana tailoring. Do not edit.
package com.edde746.plezy.model

/**
 * Orders two strings by their first code point as the server's collation (DUCET with CLDR's root tailoring) would:
 * katakana before hiragana, Kangxi radicals as their unified ideographs. Code points without a rank (and every one past
 * the BMP) follow all ranked ones, in code point order. Throws [IllegalArgumentException] for an empty string.
 */
fun ducetCompare(a: String, b: String): Int = ducetRank(firstCodePoint(a)).compareTo(ducetRank(firstCodePoint(b)))

private fun firstCodePoint(text: String): Int {
    require(text.isNotEmpty()) { "ducetCompare needs a non-empty string" }
    val high = text[0]
    if (high.isHighSurrogate() && text.length > 1 && text[1].isLowSurrogate()) {
        return 0x10000 + ((high.code - 0xD800) shl 10) + (text[1].code - 0xDC00)
    }
    return high.code
}

private fun ducetRank(codePoint: Int): Int {
    val cp = if (codePoint in KANGXI_FIRST until KANGXI_FIRST + KANGXI_UNIFIED.size) KANGXI_UNIFIED[codePoint - KANGXI_FIRST] else codePoint
    val stored = if (cp <= 0xFFFF) DUCET_RANKS[cp].code else 0
    return if (stored == 0) 0x100000 + cp else stored - 1
}

private const val KANGXI_FIRST = 0x2F00

/** The unified ideograph each Kangxi radical U+2F00–U+2FD5 decomposes to. */
private val KANGXI_UNIFIED = intArrayOf(
"""


def read_verified(source: tuple[Path, str]) -> str:
    path, digest = source
    data = gzip.decompress(path.read_bytes())
    actual = hashlib.sha256(data).hexdigest()
    if actual != digest:
        raise ValueError(f"{path.name}: sha256 {actual}, expected {digest}")
    return data.decode("utf-8")


def is_katakana(cp: int) -> bool:
    return 0x30A0 <= cp <= 0x30FF or 0x31F0 <= cp <= 0x31FF or 0xFF65 <= cp <= 0xFF9F


def parse_allkeys(text: str) -> dict[int, list[tuple[int, int, int]]]:
    """BMP single code points to their collation elements; katakana's tertiary weights lowered below hiragana's."""
    result: dict[int, list[tuple[int, int, int]]] = {}
    for line in text.split("\n"):
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("@") or ";" not in line:
            continue
        cp_part, rest = line.split(";", 1)
        cp_part = cp_part.strip()
        if " " in cp_part:
            continue
        try:
            cp = int(cp_part, 16)
        except ValueError:
            continue
        if cp > 0xFFFF:
            continue
        levels = []
        for match in WEIGHT.finditer(rest):
            tertiary = int(match.group(4), 16)
            if is_katakana(cp) and tertiary >= 0x000F:
                tertiary -= 6
            levels.append((int(match.group(2), 16), int(match.group(3), 16), tertiary))
        if not levels or all(level == (0, 0, 0) for level in levels):
            continue
        if cp in result:
            raise ValueError(f"duplicate allkeys entry for U+{cp:04x}")
        result[cp] = levels
    return result


def parse_radicals(text: str) -> tuple[list[int], dict[int, int]]:
    """CLDR's radical-stroke order of the BMP ideographs, and each Kangxi radical's unified ideograph."""
    order: list[int] = []
    kangxi: dict[int, int] = {}
    for line in text.split("\n"):
        if not RADICAL.match(line):
            continue
        eq, colon, close = line.find("="), line.find(":"), line.rfind("]")
        if eq < 0 or colon <= eq or close < 0:
            continue
        header = [ord(c) for c in line[eq + 1 : colon]]
        if len(header) >= 2 and KANGXI_FIRST <= header[0] <= KANGXI_LAST and header[1] <= 0xFFFF:
            kangxi[header[0]] = header[1]
        runes = [ord(c) for c in line[colon + 1 : close]]
        i = 0
        while i < len(runes):
            cp = runes[i]
            if cp == 0x20:
                i += 1
            elif i + 2 < len(runes) and runes[i + 1] == 0x2D:
                order.extend(value for value in range(cp, runes[i + 2] + 1) if value <= 0xFFFF)
                i += 3
            else:
                if cp <= 0xFFFF:
                    order.append(cp)
                i += 1
    return list(dict.fromkeys(order)), kangxi


def compare_weights(a: tuple[int, list], b: tuple[int, list]) -> int:
    (cp_a, levels_a), (cp_b, levels_b) = a, b
    shared = min(len(levels_a), len(levels_b))
    for i in range(shared):
        if levels_a[i][0] != levels_b[i][0]:
            return -1 if levels_a[i][0] < levels_b[i][0] else 1
    if len(levels_a) != len(levels_b):
        return -1 if len(levels_a) < len(levels_b) else 1
    for level in (1, 2):
        for i in range(shared):
            if levels_a[i][level] != levels_b[i][level]:
                return -1 if levels_a[i][level] < levels_b[i][level] else 1
    return (cp_a > cp_b) - (cp_a < cp_b)


def build_order(allkeys: dict[int, list], radical_order: list[int]) -> list[int]:
    """DUCET order with the radical-stroke ideographs placed where the implicit weights (primary 0xFB00 on) begin."""
    radicals = set(radical_order)
    ordered: list[int] = []
    inserted = False
    for cp, levels in sorted(allkeys.items(), key=functools.cmp_to_key(compare_weights)):
        if cp in radicals:
            continue
        if not inserted and levels[0][0] >= 0xFB00:
            ordered.extend(radical_order)
            inserted = True
        ordered.append(cp)
    if not inserted:
        ordered.extend(radical_order)
    return ordered


def dense_ranks(ordered: list[int]) -> list[int]:
    if len(ordered) > 0xFFFF:
        raise ValueError(f"rank table overflow: {len(ordered)} entries")
    ranks = [0] * 0x10000
    for rank, cp in enumerate(ordered):
        if ranks[cp]:
            raise ValueError(f"duplicate code point U+{cp:04x}")
        ranks[cp] = rank + 1
    return ranks


def render(ordered: list[int], kangxi: dict[int, int]) -> str:
    if sorted(kangxi) != list(range(KANGXI_FIRST, KANGXI_FIRST + len(kangxi))):
        raise ValueError("Kangxi radicals are not contiguous from U+2F00")
    out = [HEADER]
    unified = [kangxi[cp] for cp in sorted(kangxi)]
    for start in range(0, len(unified), 12):
        out.append("    " + " ".join(f"0x{value:04X}," for value in unified[start : start + 12]) + "\n")
    out.append(")\n\n")
    out.append(
        "/** One UTF-16 unit per BMP code point: its rank + 1, or 0 when it has none. "
        "Built from chunks a class file can hold. */\n"
    )
    out.append("private val DUCET_RANKS: String = buildString(0x10000) {\n")
    ranks = dense_ranks(ordered)
    lines = ["".join(f"\\u{unit:04x}" for unit in ranks[i : i + UNITS_PER_LINE]) for i in range(0, len(ranks), UNITS_PER_LINE)]
    for start in range(0, len(lines), LINES_PER_CHUNK):
        chunk = lines[start : start + LINES_PER_CHUNK]
        out.append("    append(\n")
        out.append(" +\n".join(f'        "{line}"' for line in chunk) + ",\n")
        out.append("    )\n")
    out.append("}\n")
    return "".join(out)


def main() -> None:
    radical_order, kangxi = parse_radicals(read_verified(FRACTIONAL_UCA))
    ordered = build_order(parse_allkeys(read_verified(ALLKEYS)), radical_order)
    OUTPUT.write_text(render(ordered, kangxi), encoding="utf-8")


if __name__ == "__main__":
    main()
