#!/usr/bin/env python3
"""Regenerates Plezy's launcher, status-bar and desktop icons from the SVG sources in tools/brand/.

Run through tools/brand/generate.sh, which checks the toolchain first.

Sources:
  plezy.svg                      the mark, its viewBox cropped to it;
  plezy-adaptive-foreground.svg  the mark placed on the Android adaptive icon's 108 dp canvas.
Compositions are built as SVG and rendered once per pixel size with rsvg-convert, so no output is resampled from
another bitmap.

Not generated, committed as is (Plezy's artwork, edited in its own tools):
  apple/AppIcon.icon                             the Icon Composer document (its Assets/plezy-cropped.svg is plezy.svg);
  apple/Brand.xcassets                           the tvOS layered icon and the Top Shelf images;
  android/app/src/main/res/drawable-*/banner.png the Android TV banner.
"""
from __future__ import annotations

import copy
import shutil
import struct
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BRAND = Path(__file__).resolve().parent
ANDROID_RES = ROOT / "android" / "app" / "src" / "main" / "res"
DESKTOP_ICONS = ROOT / "desktop" / "app" / "icons"
MSIX_ASSETS = ROOT / "desktop" / "app" / "packaging" / "windows" / "assets"

SVG_NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG_NS)

GENERATED = "Generated by tools/brand/generate.sh from tools/brand/*.svg. Do not edit."

# Android launcher densities: qualifier → px per dp.
DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}
# Adaptive icons: 108 dp canvas; launchers guarantee the centred 66 dp circle (tools/brand/verify.sh checks the
# layers stay inside it). The background is plain: white, and #1A1A1A in the dark theme.
ADAPTIVE_CANVAS_DP = 108.0
ADAPTIVE_BACKGROUNDS = {"drawable": "FFFFFF", "drawable-night": "1A1A1A"}
# Legacy (API 25) launcher icons: the mark on transparency in a 48 dp canvas with a 2 dp margin.
LEGACY_DP = 48.0
LEGACY_INSET_DP = 2.0
# Status-bar icons (the media notification's small icon): a 24 dp canvas with the mark inside the central 20 dp,
# white on transparent (the system uses only the alpha).
NOTIFICATION_DP = 24.0
NOTIFICATION_LIVE_DP = 20.0
# Windows and Linux: the mark on transparency with a margin of 1/16 of the canvas height.
DESKTOP_MARGIN = 1.0 / 16.0
DESKTOP_DESIGN = 1024.0
ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)
HICOLOR_SIZES = (16, 24, 32, 48, 64, 128, 256, 512)
APP_ID = "com.edde746.plezy"
# MSIX visual assets (desktop/app/packaging/windows/build-msix.ps1), in pixels. The desktop icon sits at the canvas's
# full height, centred, on transparency. The targetsize variants are the taskbar and Start icons; the altform ones stop
# the shell from plating them with the accent colour.
MSIX_SIZES = {
    "StoreLogo": (50, 50),
    "Square44x44Logo": (44, 44),
    "Square44x44Logo.scale-200": (88, 88),
    "Square150x150Logo": (150, 150),
    "Square150x150Logo.scale-200": (300, 300),
    "Square310x310Logo": (310, 310),
    "Wide310x150Logo": (310, 150),
    "SplashScreen": (620, 300),
    **{
        f"Square44x44Logo.targetsize-{size}{altform}": (size, size)
        for size in (16, 24, 32, 48, 256)
        for altform in ("", "_altform-unplated", "_altform-lightunplated")
    },
}


class BrandError(Exception):
    pass


def q(tag: str) -> str:
    return f"{{{SVG_NS}}}{tag}"


def fmt(value: float) -> str:
    """Shortest stable decimal for SVG/XML attributes."""
    text = f"{value:.6f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


class Source:
    """One brand SVG and its viewBox."""

    def __init__(self, name: str):
        self.path = BRAND / f"{name}.svg"
        self.root = ET.parse(self.path).getroot()
        try:
            _, _, self.width, self.height = (float(v) for v in self.root.get("viewBox", "").split())
        except ValueError:
            raise BrandError(f"{self.path}: needs a viewBox") from None


def fit(source: Source, x: float, y: float, width: float, height: float) -> ET.Element:
    """`source` scaled to fit the width×height box at (x, y), centred in it, as a nested <svg>."""
    nested = copy.deepcopy(source.root)
    for attr, value in (("x", x), ("y", y), ("width", width), ("height", height)):
        nested.set(attr, fmt(value))
    nested.set("preserveAspectRatio", "xMidYMid meet")
    return nested


def document(width: float, height: float, children: list[ET.Element]) -> ET.Element:
    """An SVG document with a `width`×`height` design-unit viewBox; pixel size is chosen at render time."""
    root = ET.Element(q("svg"), width=fmt(width), height=fmt(height), viewBox=f"0 0 {fmt(width)} {fmt(height)}")
    root.extend(children)
    return root


class Renderer:
    def __init__(self, workdir: Path):
        self.workdir = workdir
        self.count = 0

    def render(self, doc: ET.Element, out: Path, width: int, height: int, mode: str = "rgba") -> None:
        """Render `doc` to a `width`×`height` PNG.

        mode: rgba, or white (every pixel white, keeping the rendering's alpha).
        """
        self.count += 1
        svg = self.workdir / f"{self.count}.svg"
        ET.ElementTree(doc).write(svg, encoding="utf-8", xml_declaration=True)
        out.parent.mkdir(parents=True, exist_ok=True)
        png = out if mode == "rgba" else self.workdir / f"{self.count}.png"
        subprocess.run(
            ["rsvg-convert", "--width", str(width), "--height", str(height), "--output", str(png), str(svg)],
            check=True,
        )
        if mode == "rgba":
            return
        if mode != "white":
            raise BrandError(f"unknown render mode {mode}")
        subprocess.run(
            ["magick", str(png), "-fill", "white", "-colorize", "100", "-define", "png:color-type=6",
             "-strip", "-define", "png:exclude-chunks=date,time", str(out)],
            check=True,
        )


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def reset_dir(path: Path) -> None:
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True)


# ---------------------------------------------------------------- Android


def android(r: Renderer, mark: Source, adaptive: Source) -> None:
    if adaptive.width != adaptive.height:
        raise BrandError(f"{adaptive.path}: the adaptive icon layer must be square")
    body = LEGACY_DP - 2 * LEGACY_INSET_DP
    # The mark has no outline of its own, so the round legacy icon is the same image.
    legacy = document(LEGACY_DP, LEGACY_DP, [fit(mark, LEGACY_INSET_DP, LEGACY_INSET_DP, body, body)])
    for qualifier, density in DENSITIES.items():
        mipmap = ANDROID_RES / f"mipmap-{qualifier}"
        px = round(LEGACY_DP * density)
        for filename in ("ic_launcher.png", "ic_launcher_round.png"):
            r.render(legacy, mipmap / filename, px, px)
        px = round(ADAPTIVE_CANVAS_DP * density)
        r.render(adaptive.root, mipmap / "ic_launcher_foreground.png", px, px)
        r.render(adaptive.root, mipmap / "ic_launcher_monochrome.png", px, px, "white")

    for directory, color in ADAPTIVE_BACKGROUNDS.items():
        write_text(ANDROID_RES / directory / "ic_launcher_background.xml", adaptive_background(color))
    adaptive_icon = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {GENERATED} -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@drawable/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )
    for name in ("ic_launcher", "ic_launcher_round"):
        write_text(ANDROID_RES / "mipmap-anydpi-v26" / f"{name}.xml", adaptive_icon)

    margin = (NOTIFICATION_DP - NOTIFICATION_LIVE_DP) / 2
    glyph = document(NOTIFICATION_DP, NOTIFICATION_DP, [fit(mark, margin, margin, NOTIFICATION_LIVE_DP, NOTIFICATION_LIVE_DP)])
    for qualifier, density in DENSITIES.items():
        px = round(NOTIFICATION_DP * density)
        r.render(glyph, ANDROID_RES / f"drawable-{qualifier}" / "ic_notification.png", px, px, "white")


def adaptive_background(color: str) -> str:
    """The adaptive icon's plain background as a VectorDrawable over the 108 dp canvas."""
    size = fmt(ADAPTIVE_CANVAS_DP)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {GENERATED} -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp"\n'
        f'    android:height="{size}dp"\n'
        f'    android:viewportWidth="{size}"\n'
        f'    android:viewportHeight="{size}">\n'
        f'    <path android:fillColor="#FF{color}" android:pathData="M0,0h{size}v{size}h-{size}z" />\n'
        "</vector>\n"
    )


# ---------------------------------------------------------------- Desktop


def desktop_icon(mark: Source, width: float, height: float) -> ET.Element:
    """The Windows and Linux icon on a width×height canvas: the mark centred inside the margin."""
    margin = height * DESKTOP_MARGIN
    return document(width, height, [fit(mark, margin, margin, width - 2 * margin, height - 2 * margin)])


def desktop(r: Renderer, mark: Source) -> None:
    reset_dir(DESKTOP_ICONS)
    doc = desktop_icon(mark, DESKTOP_DESIGN, DESKTOP_DESIGN)

    r.render(doc, DESKTOP_ICONS / "plezy.png", 512, 512)
    for size in HICOLOR_SIZES:
        r.render(doc, DESKTOP_ICONS / "hicolor" / f"{size}x{size}" / "apps" / f"{APP_ID}.png", size, size)

    entries = []
    for size in ICO_SIZES:
        png = r.workdir / f"ico-{size}.png"
        r.render(doc, png, size, size)
        entries.append((size, png.read_bytes()))
    write_ico(DESKTOP_ICONS / "plezy.ico", entries)

    reset_dir(MSIX_ASSETS)
    for name, (width, height) in MSIX_SIZES.items():
        canvas = DESKTOP_DESIGN * width / height
        r.render(desktop_icon(mark, canvas, DESKTOP_DESIGN), MSIX_ASSETS / f"{name}.png", width, height)


def write_ico(path: Path, entries: list[tuple[int, bytes]]) -> None:
    """ICO with one PNG-compressed 32-bit entry per size (supported since Windows Vista)."""
    header = struct.pack("<HHH", 0, 1, len(entries))
    offset = len(header) + 16 * len(entries)
    directory = b""
    for size, data in entries:
        dim = 0 if size >= 256 else size  # 0 encodes 256
        directory += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    path.write_bytes(header + directory + b"".join(data for _, data in entries))


def main() -> int:
    mark = Source("plezy")
    adaptive = Source("plezy-adaptive-foreground")
    with tempfile.TemporaryDirectory(prefix="plezy-brand-") as tmp:
        r = Renderer(Path(tmp))
        android(r, mark, adaptive)
        desktop(r, mark)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (BrandError, subprocess.CalledProcessError) as error:
        print(f"brand: {error}", file=sys.stderr)
        sys.exit(1)
